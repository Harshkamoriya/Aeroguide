-- ─── 21. AIRLINES ─────────────────────────────────────────────────────
CREATE TABLE airlines (
    airline_id INT PRIMARY KEY,
    iata_code  CHAR(2),
    icao_code  CHAR(3),
    name       VARCHAR(80),
    country    VARCHAR(60),
    type       VARCHAR(20),
    alliance   VARCHAR(20)
);

-- ─── 22. AIRCRAFT ─────────────────────────────────────────────────────
CREATE TABLE aircraft (
    aircraft_id    INT PRIMARY KEY,
    registration   VARCHAR(10),
    airline_id     INT,
    model          VARCHAR(40),
    manufacturer   VARCHAR(20),
    seats_total    INT,
    seats_first    INT,
    seats_business INT,
    seats_economy  INT,
    range_km       INT,
    body_type      VARCHAR(20),
    FOREIGN KEY (airline_id) REFERENCES airlines(airline_id)
);

-- ─── 23. ROUTES ───────────────────────────────────────────────────────
CREATE TABLE routes (
    route_id     INT PRIMARY KEY,
    airline_id   INT,
    origin_iata  CHAR(3), origin_city VARCHAR(60),
    dest_iata    CHAR(3), dest_city VARCHAR(60),
    distance_km  INT,
    duration_min INT,
    FOREIGN KEY (airline_id) REFERENCES airlines(airline_id)
);

-- ─── 24. FLIGHT SCHEDULE ──────────────────────────────────────────────
CREATE TABLE flight_schedule (
    schedule_id    INT PRIMARY KEY,
    flight_number  VARCHAR(8),
    airline_id     INT,
    aircraft_id    INT,
    route_id       INT,
    direction      VARCHAR(10),
    terminal_id    INT,
    gate_id        INT,
    belt_id        INT,
    scheduled_time TIME,
    days_of_week   VARCHAR(20),
    status_default VARCHAR(20),
    FOREIGN KEY (airline_id)  REFERENCES airlines(airline_id),
    FOREIGN KEY (aircraft_id) REFERENCES aircraft(aircraft_id),
    FOREIGN KEY (route_id)    REFERENCES routes(route_id),
    FOREIGN KEY (terminal_id) REFERENCES terminals(terminal_id),
    FOREIGN KEY (gate_id)     REFERENCES gates(gate_id),
    FOREIGN KEY (belt_id)     REFERENCES baggage_belts(belt_id)
);


