-- ─── 1. AIRPORT ──────────────────────────────────────────────────────
CREATE TABLE airport (
    airport_id        INT PRIMARY KEY,
    iata_code         CHAR(3),
    icao_code         CHAR(4),
    name              VARCHAR(120),
    city              VARCHAR(80),
    country           VARCHAR(80),
    latitude          DECIMAL(9,6),
    longitude         DECIMAL(9,6),
    elevation_m       INT,
    total_area_sqm    INT,
    terminal_count    INT,
    runway_count      INT,
    annual_capacity   BIGINT,
    opened_year       INT,
    operator          VARCHAR(120),
    timezone          VARCHAR(40)
);

-- ─── 2. TERMINALS (with bbox coordinates) ─────────────────────────────
CREATE TABLE terminals (
    terminal_id   INT PRIMARY KEY,
    airport_id    INT,
    code          VARCHAR(8),
    name          VARCHAR(80),
    purpose       VARCHAR(40),
    floor_count   INT,
    gate_count    INT,
    area_sqm      INT,
    opened_year   INT,
    sw_x_m        DECIMAL(8,2),  sw_y_m        DECIMAL(8,2),
    ne_x_m        DECIMAL(8,2),  ne_y_m        DECIMAL(8,2),
    sw_latitude   DECIMAL(9,6),  sw_longitude  DECIMAL(9,6),
    ne_latitude   DECIMAL(9,6),  ne_longitude  DECIMAL(9,6),
    center_latitude  DECIMAL(9,6), center_longitude DECIMAL(9,6),
    FOREIGN KEY (airport_id) REFERENCES airport(airport_id)
);

-- ─── 3. FLOORS ────────────────────────────────────────────────────────
CREATE TABLE floors (
    floor_id        INT PRIMARY KEY,
    terminal_id     INT,
    floor_level     INT,
    floor_code      VARCHAR(8),
    floor_name      VARCHAR(80),
    primary_purpose VARCHAR(120),
    height_m        DECIMAL(4,2),
    area_sqm        INT,
    sw_x_m          DECIMAL(8,2), sw_y_m DECIMAL(8,2),
    ne_x_m          DECIMAL(8,2), ne_y_m DECIMAL(8,2),
    FOREIGN KEY (terminal_id) REFERENCES terminals(terminal_id)
);

-- ─── 4. ZONES (bounded sub-areas inside floors) ───────────────────────
CREATE TABLE zones (
    zone_id     INT PRIMARY KEY,
    floor_id    INT,
    zone_code   VARCHAR(12),
    zone_name   VARCHAR(80),
    sw_x_m      DECIMAL(8,2), sw_y_m DECIMAL(8,2),
    ne_x_m      DECIMAL(8,2), ne_y_m DECIMAL(8,2),
    center_x_m  DECIMAL(8,2), center_y_m DECIMAL(8,2),
    center_latitude  DECIMAL(9,6), center_longitude DECIMAL(9,6),
    area_sqm    INT,
    FOREIGN KEY (floor_id) REFERENCES floors(floor_id)
);

-- ─── 5. RUNWAYS (with geographic endpoints) ───────────────────────────
CREATE TABLE runways (
    runway_id   INT PRIMARY KEY,
    airport_id  INT,
    designation VARCHAR(8),
    length_m    INT,
    width_m     INT,
    surface     VARCHAR(20),
    heading_deg INT,
    threshold1_latitude  DECIMAL(9,6), threshold1_longitude DECIMAL(9,6),
    threshold2_latitude  DECIMAL(9,6), threshold2_longitude DECIMAL(9,6),
    threshold1_x_m  DECIMAL(8,2), threshold1_y_m DECIMAL(8,2),
    threshold2_x_m  DECIMAL(8,2), threshold2_y_m DECIMAL(8,2),
    ils_capable TINYINT,
    FOREIGN KEY (airport_id) REFERENCES airport(airport_id)
);

-- ─── 6. AIRCRAFT STANDS (apron parking positions) ─────────────────────
CREATE TABLE aircraft_stands (
    stand_id    INT PRIMARY KEY,
    code        VARCHAR(8),
    terminal_id INT,
    gate_id     INT,
    type        VARCHAR(30),
    max_aircraft VARCHAR(20),
    x_m         DECIMAL(8,2),  y_m DECIMAL(8,2),
    latitude    DECIMAL(9,6),  longitude DECIMAL(9,6),
    has_jet_bridge TINYINT,
    FOREIGN KEY (terminal_id) REFERENCES terminals(terminal_id)
);

-- ─── 7. LIFTS ─────────────────────────────────────────────────────────
CREATE TABLE lifts (
    lift_id          INT PRIMARY KEY,
    terminal_id      INT,
    lift_code        VARCHAR(12),
    lift_type        VARCHAR(30),
    capacity_persons INT,
    capacity_kg      INT,
    serves_floors    VARCHAR(40),
    location_zone_id INT,
    x_m              DECIMAL(8,2), y_m DECIMAL(8,2),
    latitude         DECIMAL(9,6), longitude DECIMAL(9,6),
    is_accessible    TINYINT,
    manufacturer     VARCHAR(40),
    install_year     INT,
    FOREIGN KEY (terminal_id) REFERENCES terminals(terminal_id)
);

-- ─── 8. ESCALATORS ────────────────────────────────────────────────────
CREATE TABLE escalators (
    escalator_id   INT PRIMARY KEY,
    terminal_id    INT,
    code           VARCHAR(12),
    from_floor_id  INT, to_floor_id INT,
    direction      VARCHAR(10),
    x_m            DECIMAL(8,2), y_m DECIMAL(8,2),
    latitude       DECIMAL(9,6), longitude DECIMAL(9,6),
    manufacturer   VARCHAR(40)
);

-- ─── 9. RESTROOMS ─────────────────────────────────────────────────────
CREATE TABLE restrooms (
    restroom_id     INT PRIMARY KEY,
    floor_id        INT,
    code            VARCHAR(12),
    type            VARCHAR(20),
    x_m             DECIMAL(8,2), y_m DECIMAL(8,2),
    latitude        DECIMAL(9,6), longitude DECIMAL(9,6),
    has_baby_change TINYINT,
    has_shower      TINYINT
);

-- ─── 10. BRANDS ───────────────────────────────────────────────────────
CREATE TABLE brands (
    brand_id          INT PRIMARY KEY,
    name              VARCHAR(60),
    category          VARCHAR(40),
    country_of_origin VARCHAR(40)
);

-- ─── 11. SHOPS ────────────────────────────────────────────────────────
CREATE TABLE shops (
    shop_id      INT PRIMARY KEY,
    shop_code    VARCHAR(12),
    brand_id     INT,
    floor_id     INT,
    zone_id      INT,
    unit_number  VARCHAR(10),
    area_sqm     INT,
    x_m          DECIMAL(8,2), y_m DECIMAL(8,2),
    latitude     DECIMAL(9,6), longitude DECIMAL(9,6),
    open_time    TIME,
    close_time   TIME,
    is_24_hours  TINYINT,
    phone_ext    VARCHAR(8),
    FOREIGN KEY (brand_id) REFERENCES brands(brand_id),
    FOREIGN KEY (floor_id) REFERENCES floors(floor_id),
    FOREIGN KEY (zone_id)  REFERENCES zones(zone_id)
);

-- ─── 12. RESTAURANTS ──────────────────────────────────────────────────
CREATE TABLE restaurants (
    restaurant_id INT PRIMARY KEY,
    code          VARCHAR(12),
    brand_id      INT,
    floor_id      INT,
    zone_id       INT,
    unit_number   VARCHAR(10),
    cuisine       VARCHAR(40),
    seats         INT,
    x_m           DECIMAL(8,2), y_m DECIMAL(8,2),
    latitude      DECIMAL(9,6), longitude DECIMAL(9,6),
    open_time     TIME, close_time TIME,
    is_24_hours   TINYINT,
    avg_price_inr INT,
    FOREIGN KEY (brand_id) REFERENCES brands(brand_id),
    FOREIGN KEY (floor_id) REFERENCES floors(floor_id)
);

-- ─── 13. LOUNGES ──────────────────────────────────────────────────────
CREATE TABLE lounges (
    lounge_id     INT PRIMARY KEY,
    code          VARCHAR(12),
    name          VARCHAR(80),
    floor_id      INT,
    zone_id       INT,
    operator      VARCHAR(60),
    tier          VARCHAR(20),
    capacity      INT,
    has_shower    TINYINT, has_bar TINYINT,
    has_meal      TINYINT, has_workspace TINYINT,
    open_time     TIME, close_time TIME,
    x_m           DECIMAL(8,2), y_m DECIMAL(8,2),
    latitude      DECIMAL(9,6), longitude DECIMAL(9,6)
);

-- ─── 14. GATES ────────────────────────────────────────────────────────
CREATE TABLE gates (
    gate_id           INT PRIMARY KEY,
    terminal_id       INT,
    gate_code         VARCHAR(8),
    floor_id          INT,
    zone_id           INT,
    has_jet_bridge    TINYINT,
    max_aircraft_size VARCHAR(20),
    x_m               DECIMAL(8,2), y_m DECIMAL(8,2),
    latitude          DECIMAL(9,6), longitude DECIMAL(9,6),
    seating_capacity  INT,
    stand_id          INT
);

-- ─── 15. CHECK-IN COUNTERS ────────────────────────────────────────────
